export function brandKind(kind: string, title: string): string {
  for (const [re, target, from] of BRAND_FIX) if (re.test(title) && from.includes(kind)) return target
  return kind
}

export function addKindHints(hints: [string[], string][]) {
  const valid = hints.filter(([words, kind]) => kind in KIND && words.length).map(([w, k]) => [w.map((s) => s.toLowerCase()), k] as [string[], string])
  KIND_HINTS.unshift(...valid)
  return valid.length
}
