export function frameTitle(platform: FramePlatform, kinds: Iterable<string>) {
  if (platform !== "selfhosted") return PLATFORMS[platform].title
  const set = new Set(kinds)
  if (set.has("k8s_workload")) return "Kubernetes"
  if (["vercel", "netlify", "cloudflare", "supabase"].some((k) => set.has(k)) && !set.has("container_service")) return "Hosting platform"
  return PLATFORMS.selfhosted.title
}

