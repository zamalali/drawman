import iconsJson from "./icons.json" with { type: "json" }
import { ROW, flowColours, isCompartment, labelColour, nodeBox } from "./flow.js"
import { edgeText, type Scene } from "./scene.js"
import { participantType } from "./sequence.js"
import { textWidth } from "./text.js"

export interface Icon { w: number; h: number; image: string }
export const ICONS = iconsJson as Record<string, Icon>

export const esc = (s: unknown) =>
  String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#x27;")

const f0 = (v: number) => Math.round(v).toString()

export const CARD_STYLE =
  "rounded=1;absoluteArcSize=1;arcSize=6;fillColor=#ffffff;strokeColor=#dddddd;shadow=1;strokeWidth=1;" +
  "html=1;whiteSpace=wrap;align=left;verticalAlign=middle;spacingLeft=50;spacingRight=6;fontSize=11;fontColor=#202124;"
const DASHED = "dashed=1;dashPattern=4 3;strokeColor=#9aa0a6;opacity=70;shadow=0;"

export const FLOW_STYLE: Record<string, string> = {
  start: "rounded=1;arcSize=50;", end: "rounded=1;arcSize=50;", process: "rounded=1;arcSize=12;",
  decision: "rhombus;", data: "shape=parallelogram;perimeter=parallelogramPerimeter;fixedSize=1;size=14;",
  document: "shape=document;boundedLbl=1;size=0.18;", database: "shape=cylinder3;boundedLbl=1;backgroundOutline=1;size=8;",
  subprocess: "shape=process;backgroundOutline=1;size=0.07;",
  initial: "ellipse;shape=startState;", final: "ellipse;shape=endState;", choice: "rhombus;", state: "rounded=1;arcSize=30;",
}

export function relationStyle(family: string | undefined, rel: string | undefined) {
  if (family === "class") {
    switch (rel) {
      case "inherits": return "endArrow=block;endFill=0;endSize=12;"
      case "implements": return "dashed=1;endArrow=block;endFill=0;endSize=12;"
      case "composition": return "startArrow=diamondThin;startFill=1;startSize=14;endArrow=none;"
      case "aggregation": return "startArrow=diamondThin;startFill=0;startSize=14;endArrow=none;"
      case "dependency": return "dashed=1;endArrow=open;endSize=10;"
      default: return "endArrow=open;endSize=10;"
    }
  }
  if (family === "er") {
    const [a, b] = rel === "one-to-one" ? ["ERmandOne", "ERmandOne"] : rel === "many-to-one" ? ["ERmany", "ERmandOne"]
      : rel === "many-to-many" ? ["ERmany", "ERmany"] : ["ERmandOne", "ERmany"]
    return `startArrow=${a};endArrow=${b};startFill=0;endFill=0;startSize=10;endSize=10;`
  }
  return "endArrow=block;endFill=1;endSize=5;"
}

export const SEQ_COLOURS: Record<string, [string, string]> = {
  service: ["#dae8fc", "#6c8ebf"], actor: ["#ffffff", "#202124"], database: ["#f5f5f5", "#666666"], queue: ["#ffe6cc", "#d79b00"],
  external: ["#f5f5f5", "#9e9e9e"], boundary: ["#e1d5e7", "#9673a6"], control: ["#e1d5e7", "#9673a6"], entity: ["#d5e8d4", "#82b366"],
}

export function iconBox(iconKey: string, cardH: number) {
  const ic = ICONS[iconKey] ?? ICONS.external_source
  const scale = 30 / Math.max(ic.w, ic.h)
  const iw = ic.w * scale, ih = ic.h * scale
  return { ic, x: 12 + (30 - iw) / 2, y: (cardH - ih) / 2, w: iw, h: ih }
}

export function buildDrawio(scene: Scene, generator = "Drawman") {
  const { facts, frames, width } = scene
  const cells = ['<mxCell id="0"/>', '<mxCell id="1" parent="0"/>']
  const vertex = (id: string, value: string, style: string, x: number, y: number, w: number, h: number, parent = "1") =>
    cells.push(
      `<mxCell id="${esc(id)}" value="${esc(value)}" style="${style}" vertex="1" parent="${parent}">` +
        `<mxGeometry x="${f0(x)}" y="${f0(y)}" width="${f0(w)}" height="${f0(h)}" as="geometry"/></mxCell>`,
    )

  const sub = [facts.subtitle, `generated by ${generator}`].filter(Boolean).join(" · ")
  vertex("title", `<b style='font-size:22px'>${esc(facts.title)}</b><br><span style='color:#5f6368'>${esc(sub)}</span>`,
    "text;html=1;align=left;verticalAlign=top;whiteSpace=wrap;fontSize=13;", 40, 30, width - 80, 70)

  const seq = scene.seq
  if (seq) {
    const labels: [string, string, string, number, number, number, number][] = []
    for (const f of seq.fragments) {
      const [x, y, w, h] = f.box
      const tab = Math.max(50, f.type.length * 8 + 26)
      vertex(`frag_${f.box.join("_")}`, f.type, `shape=umlFrame;whiteSpace=wrap;html=1;pointerEvents=0;width=${tab};height=22;` +
        "fillColor=none;strokeColor=#9aa0a6;fontStyle=1;fontSize=11;fontColor=#202124;", x, y, w, h)
      const text = "text;html=1;align=left;verticalAlign=middle;fontSize=11;fontStyle=2;fontColor=#5f6368;labelBackgroundColor=#ffffff;"
      if (f.label) labels.push([`fragl_${f.box.join("_")}`, `[${esc(f.label)}]`, text, x + tab + 8, y + 1, w - tab - 16, 20])
      f.elses.forEach((el, i) => {
        cells.push(`<mxCell id="else_${esc(f.box.join("_"))}_${i}" style="endArrow=none;dashed=1;html=1;strokeColor=#9aa0a6;" edge="1" parent="1">` +
          `<mxGeometry relative="1" as="geometry"><mxPoint x="${f0(x)}" y="${f0(el.y)}" as="sourcePoint"/><mxPoint x="${f0(x + w)}" y="${f0(el.y)}" as="targetPoint"/></mxGeometry></mxCell>`)
        if (el.label) labels.push([`elsel_${f.box.join("_")}_${i}`, `[${esc(el.label)}]`, text, x + 8, el.y + 1, w - 16, 20])
      })
    }
    for (const c of scene.cards) {
      const n = c.node
      const ll = seq.lifelines.find((l) => l.id === n.id)!
      const type = participantType(n)
      const head = type === "actor" ? "participant=umlActor;verticalAlign=top;spacingTop=36;labelBackgroundColor=#ffffff;" : type === "boundary" ? "participant=umlBoundary;"
        : type === "control" ? "participant=umlControl;" : type === "entity" ? "participant=umlEntity;" : ""
      const [fill, stroke] = SEQ_COLOURS[type] ?? SEQ_COLOURS.service
      vertex(n.id, esc(n.title), `shape=umlLifeline;perimeter=lifelinePerimeter;whiteSpace=wrap;html=1;container=0;collapsible=0;` +
        `recursiveResize=0;outlineConnect=0;portConstraint=eastwest;size=${c.box[3]};${head}fillColor=${fill};strokeColor=${stroke};` +
        `fontSize=12;fontStyle=1;fontColor=#202124;${type === "database" ? "rounded=1;arcSize=30;" : ""}${type === "external" ? "dashed=1;" : ""}`,
        c.box[0], c.box[1], c.box[2], ll.bottom - c.box[1])
    }
    seq.activations.forEach((a, i) => vertex(`act_${i}`, "", "html=1;points=[];perimeter=orthogonalPerimeter;fillColor=#ffffff;strokeColor=#5f6368;", ...a.box))
    seq.notes.forEach((nt, i) => vertex(`note_${i}`, nt.text.map(esc).join("<br>"), "shape=note;whiteSpace=wrap;html=1;size=12;fillColor=#fff2cc;" +
      "strokeColor=#d6b656;fontSize=11;align=left;spacingLeft=8;fontColor=#202124;", ...nt.box))
    for (const [id, value, style, x, y, w, h] of labels) {
      vertex(id, value, style, x, y, Math.min(w, textWidth(value.replace(/&[a-z#0-9]+;/g, "x"), 11) + 12), h)
    }
    for (const e of scene.edges) {
      const p = e.points
      const style = e.rel === "return" || e.rel === "create" ? "dashed=1;endArrow=open;endSize=10;" : e.rel === "async" ? "endArrow=open;endSize=10;" : "endArrow=block;endFill=1;endSize=8;"
      cells.push(`<mxCell id="${esc(e.id)}" value="${esc(e.label)}" style="html=1;verticalAlign=bottom;labelBackgroundColor=none;fontSize=11;` +
        `strokeColor=#5f6368;fontColor=#202124;rounded=0;${style}${e.from === e.to ? "align=left;spacingLeft=6;" : ""}" edge="1" parent="1">` +
        `<mxGeometry relative="1" as="geometry"><mxPoint x="${f0(p[0][0])}" y="${f0(p[0][1])}" as="sourcePoint"/>` +
        `<mxPoint x="${f0(p[p.length - 1][0])}" y="${f0(p[p.length - 1][1])}" as="targetPoint"/>` +
        `<Array as="points">${p.slice(1, -1).map(([x, y]) => `<mxPoint x="${f0(x)}" y="${f0(y)}"/>`).join("")}</Array></mxGeometry></mxCell>`)
    }
  }

  for (const f of frames) {
    const label = f.title + (frames.length === 1 && facts.subtitle ? ` · ${facts.subtitle}` : "")
    vertex(f.platform === "gcp" ? "gcp" : `frame_${f.platform}`, label,
      `rounded=1;arcSize=2;whiteSpace=wrap;html=1;fillColor=#ffffff;strokeColor=${f.stroke};strokeWidth=2;dashed=1;` +
        `verticalAlign=top;align=left;spacingLeft=14;spacingTop=8;fontStyle=1;fontSize=13;fontColor=${f.font};`, ...f.box)
  }
  for (const z of scene.zones) {
    vertex(`zone_${z.id}`, z.title, `rounded=1;arcSize=4;whiteSpace=wrap;html=1;fillColor=${z.fill};strokeColor=${z.stroke};` +
      "verticalAlign=top;fontStyle=1;fontSize=12;spacingTop=6;", ...z.box)
  }
  for (const c of seq ? [] : scene.cards) {
    const n = c.node
    const [x, y, w, h] = c.box
    if (facts.flow) {
      const shape = n.shape ?? "process"
      const [fill, stroke] = flowColours(n)
      const dashed = n.status === "planned" || n.status === "bypassed" ? "dashed=1;dashPattern=4 3;" : ""
      const nb = nodeBox(n)
      if (isCompartment(shape)) {
        const head = nb.head!
        const name = nb.stereo ? `<i style='font-weight:normal;font-size:11px'>${esc(nb.stereo)}</i><br>${esc(nb.lines[0])}` : esc(nb.lines[0])
        vertex(n.id, name, `swimlane;fontStyle=${shape === "abstract" ? 3 : 1};align=center;verticalAlign=top;childLayout=stackLayout;` +
          `horizontal=1;startSize=${head};horizontalStack=0;resizeParent=1;resizeParentMax=0;resizeLast=0;collapsible=0;` +
          `marginBottom=0;whiteSpace=wrap;html=1;fillColor=${fill};strokeColor=${stroke};swimlaneFillColor=#ffffff;fontSize=13;` +
          `fontColor=#202124;rounded=1;arcSize=4;${dashed}`, x, y, w, h)
        const row = "text;strokeColor=none;fillColor=none;align=left;verticalAlign=middle;spacingLeft=8;spacingRight=4;" +
          "overflow=hidden;rotatable=0;points=[[0,0.5],[1,0.5]];portConstraint=eastwest;whiteSpace=wrap;html=1;fontSize=12;fontColor=#202124;"
        let ry = head
        nb.fields!.forEach((f, i) => {
          vertex(`${n.id}_f${i}`, esc(f), row + (/^PK /.test(f) ? "fontStyle=5;" : ""), 0, ry, w, ROW, esc(n.id))
          ry += ROW
        })
        if (nb.methods!.length) {
          if (!nb.fields!.length) ry += ROW
          vertex(`${n.id}_div`, "", "line;strokeWidth=1;fillColor=none;align=left;verticalAlign=middle;spacingTop=-1;spacingLeft=3;" +
            `spacingRight=3;rotatable=0;labelPosition=right;points=[];portConstraint=eastwest;strokeColor=${stroke};`, 0, ry, w, 8, esc(n.id))
          ry += 8
          nb.methods!.forEach((m, i) => { vertex(`${n.id}_m${i}`, esc(m), row, 0, ry, w, ROW, esc(n.id)); ry += ROW })
        }
        continue
      }
      const value = shape === "state"
        ? `<b>${nb.lines.map(esc).join("<br>")}</b>${nb.sub?.length ? `<br><span style='font-size:10px;color:#5f6368'>${nb.sub.map(esc).join("<br>")}</span>` : ""}`
        : nb.lines.map(esc).join("<br>")
      cells.push(
        `<mxCell id="${esc(n.id)}" value="${esc(value)}"${n.detail ? ` tooltip="${esc(n.detail)}"` : ""} ` +
          `style="${FLOW_STYLE[shape] ?? FLOW_STYLE.process}whiteSpace=wrap;html=1;fillColor=${fill};strokeColor=${stroke};strokeWidth=1.2;` +
          `fontSize=12;fontColor=#202124;${dashed}" ` +
          `vertex="1" parent="1"><mxGeometry x="${f0(x)}" y="${f0(y)}" width="${f0(w)}" height="${f0(h)}" as="geometry"/></mxCell>`,
      )
      continue
    }
    const label = `<b>${esc(n.title)}</b><br><span style='color:#5f6368;font-size:10px'>${esc(n.detail)}</span>`
    vertex(n.id, label, CARD_STYLE + (n.status === "bypassed" || n.status === "planned" ? DASHED : ""), x, y, w, h)
    const ib = iconBox(c.icon, h)
    vertex(`${n.id}_icon`, "", `shape=image;html=1;imageAspect=0;aspect=fixed;image=${ib.ic.image};`, ib.x, ib.y, ib.w, ib.h, esc(n.id))
  }
  const box = new Map(scene.cards.map((c) => [c.node.id, c.box]))
  for (const e of seq ? [] : scene.edges) {
    const pts = e.points
    const [sx, sy, sw, sh] = box.get(e.from)!
    const [tx, ty, tw, th] = box.get(e.to)!
    const ex = (pts[0][0] - sx) / sw, ey = (pts[0][1] - sy) / sh
    const nx = (pts[pts.length - 1][0] - tx) / tw, ny = (pts[pts.length - 1][1] - ty) / th
    const waypoints = pts.slice(1, -1).map(([x, y]) => `<mxPoint x="${f0(x)}" y="${f0(y)}"/>`).join("")
    const flowLabel = facts.flow
      ? `fontSize=11;fontStyle=1;fontColor=${facts.flow.family === "flowchart" ? labelColour(e.label) : "#5f6368"};labelBackgroundColor=#ffffff;`
      : "fontSize=10;fontStyle=1;fontColor=#1a73e8;labelBackgroundColor=#ffffff;"
    cells.push(
      `<mxCell id="${esc(e.id)}" value="${esc(edgeText(e, !!facts.flow))}" tooltip="${esc(e.description)}" ` +
        `style="edgeStyle=none;rounded=1;arcSize=10;html=1;strokeColor=#5f6368;jumpStyle=arc;jumpSize=8;` +
        `strokeWidth=1.5;${relationStyle(facts.flow?.family, e.rel)}${flowLabel}` +
        `exitX=${ex.toFixed(4)};exitY=${ey.toFixed(4)};exitDx=0;exitDy=0;exitPerimeter=0;` +
        `entryX=${nx.toFixed(4)};entryY=${ny.toFixed(4)};entryDx=0;entryDy=0;entryPerimeter=0;" ` +
        `edge="1" parent="1" source="${esc(e.from)}" target="${esc(e.to)}">` +
        `<mxGeometry x="${e.labelPos.toFixed(3)}" relative="1" as="geometry"><Array as="points">${waypoints}</Array></mxGeometry></mxCell>`,
    )
  }
  const titles = new Map(facts.nodes.map((n) => [n.id, n.title]))
  const rows = scene.edges.map((e) =>
    `<tr><td style='padding:3px 8px;color:#1a73e8'><b>${esc(e.id)}</b></td>` +
    `<td style='padding:3px 8px'>${esc(titles.get(e.from))} → ${esc(titles.get(e.to))}</td>` +
    `<td style='padding:3px 8px'>${esc(e.protocol)}</td>` +
    `<td style='padding:3px 8px;color:#5f6368'>${esc(e.description || e.label)}</td></tr>`).join("")
  if (scene.edges.length && !facts.flow && !seq) {
    vertex("legend", `<b>${facts.groups ? "Connections" : "Interfaces"}</b><table style='font-size:11px;margin-top:6px'>${rows}</table>`,
      "rounded=1;arcSize=2;whiteSpace=wrap;html=1;fillColor=#ffffff;strokeColor=#dddddd;align=left;verticalAlign=top;" +
        "spacing=12;fontSize=12;", ...scene.legend)
  }
  const xml =
    `<mxfile host="drawman" type="device"><diagram id="arch" name="Architecture">` +
    `<mxGraphModel dx="1600" dy="1000" grid="0" gridSize="10" guides="1" tooltips="1" connect="1" arrows="1" ` +
    `fold="1" page="0" pageScale="1" math="0" shadow="0"><root>${cells.join("")}</root></mxGraphModel></diagram></mxfile>`
  return {
    xml,
    stats: {
      zones: scene.zones.length,
      cards: scene.cards.length,
      edges: scene.edges.length,
      unrouted: scene.unrouted.length,
      dropped: facts.dropped.length,
      bytes: xml.length,
    },
  }
}
